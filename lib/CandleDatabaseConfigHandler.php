<?php

/** Keep cached configuration identical for all semesters; select the DSN at runtime. */
class CandleDatabaseConfigHandler extends sfDatabaseConfigHandler
{
    public function execute($configFiles)
    {
        list($includes, $databases) = $this->parse($configFiles);
        $code = "<?php\n// Generated by CandleDatabaseConfigHandler.\n";
        foreach ($includes as $include) {
            $code .= 'require_once '.var_export($include, true).";\n";
        }
        $code .= "return array(\n";
        foreach ($databases as $name => $database) {
            $parameters = var_export($database[1], true);
            $constructor = $name === 'doctrine'
                ? 'CandleArchive::createDatabase('.var_export($database[0], true).', '.$parameters.')'
                : 'new '.$database[0].'('.$parameters.')';
            $code .= var_export($name, true).' => '.$constructor.",\n";
        }
        return $code.");\n";
    }
}
